def fetch_rss(source_name, url):
    """RSS-лента -> список (published, title, summary, link)."""
    resp = requests.get(url, timeout=(10, 15), headers=UA)
    resp.raise_for_status()
    parsed = feedparser.parse(resp.content)
    items = []
    for e in parsed.entries:
        published = None
        for key in ("published_parsed", "updated_parsed"):
            t = e.get(key)
            if t:
                published = dt.datetime.fromtimestamp(time.mktime(t), tz=dt.timezone.utc)
                break
        title = e.get("title", "").strip()
        link = e.get("link", "").strip()
        summary = re.sub(r"<[^>]+>", " ", e.get("summary", ""))[:400]
        if title and link:
            items.append((published, title, summary, link))
    return items


def fetch_telegram(source_name, username):
    """Публичный Telegram-канал через t.me/s/ -> список (published, title, summary, link)."""
    resp = requests.get(f"https://t.me/s/{username}", timeout=(10, 15), headers=UA)
    resp.raise_for_status()
    soup = BeautifulSoup(resp.text, "html.parser")
    items = []
    for msg in soup.select(".tgme_widget_message_wrap"):
        text_el = msg.select_one(".tgme_widget_message_text")
        time_el = msg.select_one("time[datetime]")
        link_el = msg.select_one("a.tgme_widget_message_date")
        if not (text_el and time_el and link_el):
            continue
        text = text_el.get_text(" ", strip=True)
        if len(text) < 40:  # реакции, репосты без текста, служебные посты
            continue
        try:
            published = dt.datetime.fromisoformat(time_el["datetime"])
        except Exception:
            published = None
        # Заголовок = первое предложение или первые ~130 знаков
        title = re.split(r"(?<=[.!?])\s", text, maxsplit=1)[0][:130].strip()
        if len(title) < 25:
            title = text[:130].strip()
        items.append((published, title, text[:400], link_el.get("href", "")))
    # На странице сообщения идут от старых к новым, разворачиваю
    return list(reversed(items))


def fetch_source(kind, source_name, addr):
    try:
        if kind == "rss":
            return fetch_rss(source_name, addr)
        return fetch_telegram(source_name, addr)
    except Exception as e:
        print(f"  [пропуск] {source_name} ({addr}): {type(e).__name__}")
        return []


