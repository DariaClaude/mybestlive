SENT_FILE = "sent_links.json"
SENT_KEEP = 500         # сколько последних ссылок помнить
SENT_TITLES_KEEP = 300  # сколько последних заголовков помнить (дедуп по содержанию)


def load_sent():
    """Возвращает (links, titles): отправленные ссылки и наборы слов заголовков."""
    if os.path.exists(SENT_FILE):
        try:
            with open(SENT_FILE, encoding="utf-8") as f:
                data = json.load(f)
                return data.get("links", []), data.get("titles", [])
        except Exception:
            return [], []
    return [], []


def save_sent(links, titles):
    with open(SENT_FILE, "w", encoding="utf-8") as f:
        json.dump({"links": links[-SENT_KEEP:],
                   "titles": titles[-SENT_TITLES_KEEP:]},
                  f, ensure_ascii=False, indent=1)


def _stem(word):
    return word[:6]


def title_words(title):
    """Значимые слова заголовка (основы по 6 знаков) для сравнения на дубли.
    Имена собственные (слова с большой буквы) помечены звёздочкой:
    «Росатома» и «Росатом» дают одну основу «*росато»."""
    words = []
    for w in re.findall(r"[А-ЯЁа-яёA-Za-z0-9-]+", title):
        if len(w) <= 3:
            continue
        stem = _stem(normalize(w))
        words.append("*" + stem if w[0].isupper() else stem)
    return words


def is_duplicate_title(words, sent_titles):
    """Та же новость под другой ссылкой: пересечение основ слов >= 60%
    или три и более общих имени собственных."""
    ws = set(words)
    if len(ws) < 3:
        return False
    proper = {w for w in ws if w.startswith("*")}
    for prev in sent_titles:
        ps = set(prev)
        if not ps:
            continue
        if len(ws & ps) / min(len(ws), len(ps)) >= 0.6:
            return True
        if len(proper & ps) >= 3:
            return True
    return False


def collect_news():
    cutoff = dt.datetime.now(dt.timezone.utc) - dt.timedelta(hours=HOURS_BACK)
    sent_links_list, sent_titles = load_sent()
    already_sent = set(sent_links_list)

    # Каждая лента загружается один раз, даже если стоит в нескольких разделах
    unique = {}
    for sources in SOURCES.values():
        for kind, source_name, addr in sources:
            unique.setdefault((kind, addr), source_name)
    fetched = {}
    with ThreadPoolExecutor(max_workers=10) as pool:
        futures = {key: pool.submit(fetch_source, key[0], name, key[1])
                   for key, name in unique.items()}
        for key, fut in futures.items():
            try:
                fetched[key] = fut.result(timeout=25)
            except FutTimeout:
                print(f"  [таймаут] {unique[key]}")
                fetched[key] = []

    digest = {}
    seen_links = set()
    evaluated = set()
    new_titles = []
    per_source = {}       # (раздел, источник) -> сколько уже взято
    # Кандидаты после словарного отсева; ИИ выносит финальный вердикт
    candidates = {}       # id -> (категория, заголовок, фрагмент)
    placed = []           # (категория, id, сигнал, источник, заголовок, ссылка, вне_ИИ)
    next_id = 0

    for category, sources in SOURCES.items():
        for kind, source_name, addr in sources:
            for published, title, summary, link in fetched.get((kind, addr), []):
                if published and published < cutoff:
                    continue
                if link in evaluated or link in already_sent:
                    continue
                evaluated.add(link)
                # Дубль по содержанию: та же новость под другой ссылкой
                words = title_words(title)
                if is_duplicate_title(words, sent_titles + new_titles):
                    continue
                target, signal = passes_filters(title, summary, category, source_name)
                if target is None:
                    continue
                if per_source.get((target, source_name), 0) >= MAX_PER_SOURCE:
                    continue
                per_source[(target, source_name)] = per_source.get((target, source_name), 0) + 1
                seen_links.add(link)
                new_titles.append(words)
                skip_ai = (signal == "🎯")  # персоны из списка не переспрашиваем
                if not skip_ai:
                    candidates[next_id] = (target, title, summary)
                placed.append((target, next_id, signal, source_name, title, link, skip_ai))
                next_id += 1

    approved = ai_review(candidates)

    for category, item_id, signal, source_name, title, link, skip_ai in placed:
        if not skip_ai and approved is not None and item_id not in approved:
            continue
        digest.setdefault(category, []).append((signal, source_name, title, link))

    # Разделы в порядке SOURCES, внутри — по приоритету сигнала
    priority = {"🎯": 0, "🏛": 1, "👤": 2, "⚠️": 3, "📋": 4, "🚀": 5, "": 9}
    digest = {cat: sorted(digest[cat], key=lambda x: priority.get(x[0], 9))
              for cat in SOURCES if cat in digest}

    # Запоминаю отправленное, чтобы не повторяться в следующих выпусках
    if not DRY_RUN:
        save_sent(sent_links_list + sorted(seen_links), sent_titles + new_titles)
    return digest


def build_messages(digest):
    today = dt.datetime.now().strftime("%d.%m.%Y")
    header = (
        f"📰 <b>Отраслевой дайджест за {today}</b>\n"
        f"<i>🎯 персоны · 🏛 заявления властей · 👤 кадры · ⚠️ проблемы · 📋 планы · 🚀 старты проектов</i>\n"
    )

    if not digest:
        return [header + "\nЗа последние сутки релевантных новостей не найдено."]

    messages = []
    current = header
    for category, items in digest.items():
        block = f"\n<b>{html.escape(category)}</b>\n"
        for signal, source, title, link in items:
            bullet = signal if signal else "•"
            block += f'{bullet} <a href="{html.escape(link)}">{html.escape(title)}</a> <i>({html.escape(source)})</i>\n'
        if len(current) + len(block) > 3800:
            messages.append(current)
            current = block
        else:
            current += block

    if current.strip():
        messages.append(current)
    return messages


def send_message(chat_id, text):
    resp = requests.post(
        f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage",
        json={
            "chat_id": chat_id,
            "text": text,
            "parse_mode": "HTML",
            "disable_web_page_preview": True,
        },
        timeout=30,
    )
    if not resp.ok:
        print("Ошибка отправки:", resp.status_code, resp.text)
    resp.raise_for_status()


def load_subscribers():
    """Список получателей: subscribers.json + основной chat_id из секрета."""
    subs = {int(CHAT_ID)} if CHAT_ID else set()
    if os.path.exists("subscribers.json"):
        try:
            with open("subscribers.json", encoding="utf-8") as f:
                subs.update(json.load(f).get("subscribers", []))
        except Exception as e:
            print("Не удалось прочитать subscribers.json:", type(e).__name__)
    return sorted(subs)


def main():
    digest = collect_news()
    total = sum(len(v) for v in digest.values())
    print(f"Отобрано новостей: {total} в {len(digest)} разделах")
    messages = build_messages(digest)

    if DRY_RUN:
        print("DRY_RUN: выпуск не отправляется и не сохраняется.\n")
        for msg in messages:
            print(re.sub(r"<[^>]+>", "", msg))
        return

    # Кэш последнего выпуска: его мгновенно отдаёт webhook новым подписчикам
    with open("digest_latest.json", "w", encoding="utf-8") as f:
        json.dump({"generated_at": dt.datetime.now(dt.timezone.utc).isoformat(),
                   "messages": messages}, f, ensure_ascii=False, indent=2)

    for chat_id in load_subscribers():
        for msg in messages:
            try:
                send_message(chat_id, msg)
            except Exception as e:
                print(f"Не удалось отправить {chat_id}: {type(e).__name__}")
                break
            time.sleep(1)
    print("Дайджест отправлен.")


if __name__ == "__main__":
    main()
