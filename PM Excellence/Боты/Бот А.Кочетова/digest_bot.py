# Синтаксис ключевых слов во всех списках ниже:
#   "мост"        — подстрока (совпадёт и внутри слова: «самостоятельно»);
#   "~мост"       — только с начала слова: «мост», «мостов», но не «самостоятельно»;
#   "~газ(?!ет)"  — после ~ допустимо регулярное выражение;
#   "^новости"    — регулярное выражение как есть (^ = начало текста).
# ---------------------------------------------------------------


def normalize(text):
    return text.lower().replace("ё", "е")


@lru_cache(maxsize=4096)
def _pattern(kw):
    if kw.startswith("~"):
        return re.compile(r"\b(?:" + kw[1:] + ")")
    return re.compile(kw)


def contains(text, kw):
    if kw[:1] in ("~", "^"):
        return _pattern(kw).search(text) is not None
    return kw in text


def matches(text, keywords):
    """Есть ли в тексте хотя бы одно ключевое слово. Пустой список = да."""
    if not keywords:
        return True
    return any(contains(text, k) for k in keywords)


def count_matches(text, keywords):
    return sum(1 for k in keywords if contains(text, k))


