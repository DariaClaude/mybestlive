def detect_signal(text):
    """Возвращает эмодзи сигнала или пустую строку. Порядок = приоритет."""
    # Заявление власти: чиновник + требование + привязка к проекту
    if match_official_demand(text) and matches(text, PROJECT_CONTEXT):
        return "🏛"
    for emoji, keywords in SIGNALS:
        if matches(text, keywords):
            # "назначен" про транспорт, а не про людей: дополнительные поезда, рейсы
            if emoji == "👤" and matches(text, ("~поезд", "~рейс", "электрич", "автобус",
                                               "маршрут", "~состав", "перрон")):
                continue
            # Кадры: только ключевые компании/ведомства и только про должность
            if emoji == "👤" and not (matches(text, KEY_ORGS) and matches(text, POSITION_WORDS)):
                continue
            # Проблемы только в крупных и мегапроектах, и не про остановку транспорта
            if emoji == "⚠️" and (not matches(text, MEGA_CONTEXT) or is_operations_disruption(text)):
                continue
            return emoji
    if match_deadline_shift(text) and matches(text, MEGA_CONTEXT):
        return "⚠️"
    if match_cost_overrun(text) and matches(text, MEGA_CONTEXT):
        return "⚠️"
    if match_project_start(text):
        return "🚀"
    return ""


