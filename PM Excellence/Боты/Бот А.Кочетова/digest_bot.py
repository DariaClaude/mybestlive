def classify(text, home_category, is_general):
    """Возвращает раздел для новости или None (нет тематики — отсев)."""
    scores = {cat: count_matches(text, SECTOR_KEYWORDS[cat]) for cat in SECTOR_ORDER}
    best = max(SECTOR_ORDER, key=lambda c: (scores[c], -SECTOR_ORDER.index(c)))
    if is_general:
        return best if scores[best] > 0 else None
    # профильный источник: свой раздел, если он подтверждён или ничего другого не найдено
    if scores[home_category] > 0 or scores[best] == 0:
        return home_category
    return best


