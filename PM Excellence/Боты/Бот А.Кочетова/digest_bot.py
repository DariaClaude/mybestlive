def ai_review(candidates):
    """Отдаёт Claude список кандидатов, возвращает множество одобренных id.
    None = ИИ недоступен (нет ключа или ошибка), тогда работаем по словарям."""
    key = os.environ.get("ANTHROPIC_API_KEY", "").strip()
    if not key or not candidates:
        return None
    listing = [
        {"id": i, "раздел": cat, "заголовок": title, "текст": summary[:250]}
        for i, (cat, title, summary) in candidates.items()
    ]
    try:
        resp = requests.post(
            "https://api.anthropic.com/v1/messages",
            headers={
                "x-api-key": key,
                "anthropic-version": "2023-06-01",
                "content-type": "application/json",
            },
            json={
                "model": AI_MODEL,
                "max_tokens": 1000,
                "messages": [{
                    "role": "user",
                    "content": AI_PROMPT + "\n\n" + json.dumps(listing, ensure_ascii=False),
                }],
            },
            timeout=90,
        )
        if not resp.ok:
            print(f"ИИ-проверка недоступна: HTTP {resp.status_code} {resp.text[:200]}")
            return None
        text = "".join(b.get("text", "") for b in resp.json().get("content", []))
        text = text.replace("```json", "").replace("```", "").strip()
        keep = set(json.loads(text).get("keep", []))
        print(f"ИИ-проверка: {len(candidates)} кандидатов -> {len(keep)} одобрено")
        return keep
    except Exception as e:
        print(f"ИИ-проверка недоступна ({type(e).__name__}: {e}), работаем по словарям")
        return None


