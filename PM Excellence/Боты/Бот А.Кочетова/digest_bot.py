def passes_filters(title, summary, category, source_name):
    """Возвращает (раздел или None, эмодзи сигнала).
    В дайджест попадают ТОЛЬКО сигнальные новости:
    🎯 персоны, 🏛 заявления властей, 👤 кадры, ⚠️ проблемы, 📋 планы, 🚀 старты.
    Раздел может отличаться от исходного: общеделовые источники раскладываются
    по тематике, профильные переносятся при явном несовпадении.
    """
    text = normalize(title + " " + summary)

    # Персоны из списка мониторинга: высший приоритет, без остальных фильтров
    if match_person(text):
        return category, "🎯"

    if matches(text, EXCLUDE_KEYWORDS):
        return None, ""
    if is_stock_news(text):
        return None, ""
    if is_foreign_only(text):
        return None, ""

    signal = detect_signal(text)
    if not signal:
        return None, ""

    # Планы (📋) только про крупные масштабы: миллиарды или мегапроекты
    if signal == "📋" and not matches(text, ("млрд", "трлн", "мегапроект", "крупнейш")):
        return None, ""

    target = classify(text, category, source_name in GENERAL_SOURCES)
    if target is None:
        return None, ""
    return target, signal


