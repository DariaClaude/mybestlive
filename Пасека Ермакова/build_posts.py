    r = p.add_run("ПОСТ %d" % num); r.bold = True; r.font.size = Pt(11); r.font.color.rgb = AMBER
    r2 = p.add_run("     " + platform); r2.font.size = Pt(9); r2.font.color.rgb = MUTED
    # headline
    p = doc.add_paragraph(); r = p.add_run(headline); r.bold = True; r.font.size = Pt(16); r.font.color.rgb = DARK
    p.space_after = Pt(6)
    # image (exact name, else match by prefix — WEBP files have full UUID names)
    imgpath = os.path.join(IMG, img + ".jpg")
    if not os.path.exists(imgpath):
        matches = sorted(glob.glob(os.path.join(IMG, img + "*.jpg")))
        imgpath = matches[0] if matches else None
    if imgpath and os.path.exists(imgpath):
        pic = doc.add_paragraph(); pic.alignment = WD_ALIGN_PARAGRAPH.CENTER
        pic.add_run().add_picture(imgpath, width=Cm(13.5))
    else:
        raise SystemExit("MISSING IMAGE for post %d: %s" % (num, img))
    # body
    for para in paras:
        pp = doc.add_paragraph(); rr = pp.add_run(para); rr.font.size = Pt(11)
        pp.paragraph_format.space_after = Pt(6)
    # tags
    tp = doc.add_paragraph(); tr = tp.add_run(tags); tr.italic = True; tr.font.size = Pt(10); tr.font.color.rgb = AMBER

